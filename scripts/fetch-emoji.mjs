// Downloads Google's animated Noto emoji (Lottie, CC BY 4.0) for every emoji used in videos/*.json
// (headline + bigText) into public/lottie/, and writes src/emoji.generated.ts mapping emoji -> file.
// Emoji without an animated version stay as normal (static) emoji. Runs from scripts/sync-videos.mjs.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const isEmoji = (g) => /\p{Extended_Pictographic}/u.test(g);
const codeFor = (g) =>
  [...g]
    .map((c) => c.codePointAt(0).toString(16))
    .filter((c) => c !== "fe0f")
    .join("_");

export async function fetchEmoji() {
  mkdirSync("public/lottie", { recursive: true });
  const segmenter = new Intl.Segmenter("en", { granularity: "grapheme" });
  const wanted = new Set();
  for (const f of existsSync("videos") ? readdirSync("videos").filter((x) => x.endsWith(".json")) : []) {
    const script = JSON.parse(readFileSync(`videos/${f}`, "utf8")).script;
    for (const s of script.scenes) {
      for (const text of [s.headline, s.bigText, JSON.stringify(s.visual ?? "")]) {
        for (const { segment } of segmenter.segment(text ?? "")) if (isEmoji(segment)) wanted.add(segment);
      }
    }
  }

  const missingFile = "public/lottie/missing.json"; // emoji Google has no animation for (don't re-ask every time)
  const missing = new Set(existsSync(missingFile) ? JSON.parse(readFileSync(missingFile, "utf8")) : []);
  const map = {};
  for (const e of wanted) {
    const code = codeFor(e);
    const file = `public/lottie/${code}.json`;
    if (!existsSync(file) && !missing.has(code)) {
      try {
        const res = await fetch(`https://fonts.gstatic.com/s/e/notoemoji/latest/${code}/lottie.json`);
        if (res.ok) writeFileSync(file, await res.text());
        else if (res.status === 404) missing.add(code);
      } catch {
        // offline: keep the static emoji for now
      }
    }
    if (existsSync(file)) map[e] = `lottie/${code}.json`;
  }
  writeFileSync(missingFile, JSON.stringify([...missing]));
  writeFileSync(
    "src/emoji.generated.ts",
    `// AUTO-GENERATED by scripts/fetch-emoji.mjs. Do not edit, do not commit.\nexport const animatedEmoji: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`,
  );
  return map;
}
